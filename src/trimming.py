def criterion(n):
    """試行数 n に対する SD の倍数．n が 100 を超えるときは n = 100 の値．"""
    return CRITERION[min(n, 100) - 1]


def keep_mask(rts):
    """残す試行の真偽値の配列を返す．平均 ± k × SD の外側を除く（trimr と同じく境界も除く）．"""
    rts = np.asarray(rts, dtype=float)
    n = len(rts)
    if n < 2:
        return np.ones(n, dtype=bool)
    k = criterion(n)
    mean = rts.mean()
    sd = rts.std(ddof=1)
    return (rts > mean - k * sd) & (rts < mean + k * sd)
